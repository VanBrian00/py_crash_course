name = "ada lovelace"
print(name.title())

#dengan menambahkan .title (metode title) di belakan variabel
#itu akan buat jadi : Ada Lovelace, huruh kapital di awal.
#sebuah metode harus diikuti tanda kurung di belakang.
#ditujukan sebagai tempat dari informasi tambahan.
#jika tidak ada info tambahan dikosongkan seperti contoh di atas.
#jadi metode title untuk mengubah semua kata di
#variabel dengan tipe data string menjadi 
#title case (setiap kata dimulai dengan huruf kapital).

print(name.upper())
print(name.lower())

#untuk metode upper itu buat bikin semua huruf jadi kapital.
#untuk metode lower bikin semua huruf jadi huruf kecil semua.
